[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function Assert-Equal {
    param(
        [Parameter(Mandatory)]$Expected,
        [Parameter(Mandatory)]$Actual,
        [Parameter(Mandatory)][string]$Message
    )

    if ($Expected -ne $Actual) {
        throw "$Message Expected '$Expected', got '$Actual'."
    }
}

function Assert-True {
    param(
        [Parameter(Mandatory)][bool]$Condition,
        [Parameter(Mandatory)][string]$Message
    )

    if (-not $Condition) {
        throw $Message
    }
}

$testRoot = Join-Path ([System.IO.Path]::GetTempPath()) ('wiztree-summary-test-' + [guid]::NewGuid().ToString('N'))
$resolvedTestRoot = [System.IO.Path]::GetFullPath($testRoot)
$tempRoot = [System.IO.Path]::GetFullPath([System.IO.Path]::GetTempPath())
if (-not $resolvedTestRoot.StartsWith($tempRoot, [System.StringComparison]::OrdinalIgnoreCase)) {
    throw "Refusing to create a test directory outside the system temp path: $resolvedTestRoot"
}

[System.IO.Directory]::CreateDirectory($resolvedTestRoot) | Out-Null
$fixture = Join-Path $resolvedTestRoot 'wiztree.csv'
$invalidFixture = Join-Path $resolvedTestRoot 'invalid.csv'
$negativeFixture = Join-Path $resolvedTestRoot 'negative.csv'
$ownedMarker = Join-Path $resolvedTestRoot '.owned-by-wiztree-summary-tests'
$scriptPath = Join-Path (Split-Path $PSScriptRoot -Parent) 'Summarize-WizTreeCsv.ps1'

try {
    [System.IO.File]::WriteAllText($ownedMarker, 'owned test directory', [System.Text.UTF8Encoding]::new($false))
    $manyRows = 1..150 | ForEach-Object {
        '"C:\Many\item-{0:D3}.bin",{0},{0},2026-08-31,32,0,0' -f $_
    }
    $content = @'
Generated by WizTree 4.31 2026-08-31
File Name,Size,Allocated,Date Modified,Attributes,Files,Folders
"C:\Alpha\",320,352,2026-08-31,16,3,1
"C:\Alpha\one.bin",60,64,2026-08-31,32,0,0
"C:\Alpha\two.bin",30,32,2026-08-31,32,0,0
"C:\Alpha\sub\",250,256,2026-08-31,16,1,0
"C:\Alpha\sub\deep.bin",250,256,2026-08-31,32,0,0
"C:\Beta\",10,16,2026-08-31,16,1,0
"C:\Beta\item.txt",10,16,2026-08-31,32,0,0
'@
    $content += "`n" + ($manyRows -join "`n")
    [System.IO.File]::WriteAllText($fixture, $content, [System.Text.UTF8Encoding]::new($false))

    $summary = & $scriptPath -CsvPath $fixture -Roots @('C:\Alpha', 'C:\Missing', 'C:\Many') -Top 2
    $alpha = @($summary.Roots | Where-Object Root -ieq 'C:\Alpha')[0]
    $missing = @($summary.Roots | Where-Object Root -ieq 'C:\Missing')[0]
    $many = @($summary.Roots | Where-Object Root -ieq 'C:\Many')[0]

    Assert-Equal -Expected 3 -Actual $alpha.DirectItems -Message 'Direct child count is incorrect.'
    Assert-Equal -Expected 352 -Actual $alpha.AllocatedBytes -Message 'Allocated byte total is incorrect.'
    Assert-Equal -Expected 2 -Actual $alpha.Top.Count -Message 'Top limit was not applied.'
    Assert-Equal -Expected 'sub' -Actual $alpha.Top[0].Name -Message 'Top item ordering is incorrect.'
    Assert-Equal -Expected 0 -Actual $missing.DirectItems -Message 'Missing roots must return an empty summary.'
    Assert-True -Condition (-not ($alpha.Top.Path -contains 'C:\Alpha\sub\deep.bin')) -Message 'A grandchild was counted as a direct child.'
    Assert-Equal -Expected 150 -Actual $many.DirectItems -Message 'Large-root direct child count is incorrect.'
    Assert-Equal -Expected 2 -Actual $many.Top.Count -Message 'Large-root Top results were not bounded.'
    Assert-Equal -Expected 'item-150.bin' -Actual $many.Top[0].Name -Message 'Large-root Top ordering is incorrect.'

    [System.IO.File]::WriteAllText($invalidFixture, "not a WizTree export`nFile Name,Size,Allocated", [System.Text.UTF8Encoding]::new($false))
    $invalidRejected = $false
    try {
        & $scriptPath -CsvPath $invalidFixture -Roots @('C:\Alpha') | Out-Null
    }
    catch {
        $invalidRejected = $_.Exception.Message -match 'does not identify a WizTree export'
    }
    Assert-True -Condition $invalidRejected -Message 'An invalid WizTree banner was not rejected.'

    [System.IO.File]::WriteAllText($negativeFixture, @'
Generated by WizTree 4.31 2026-08-31
File Name,Size,Allocated,Date Modified,Attributes,Files,Folders
"C:\Alpha\bad.bin",-1,-1,2026-08-31,32,0,0
'@, [System.Text.UTF8Encoding]::new($false))
    $negativeRejected = $false
    try {
        & $scriptPath -CsvPath $negativeFixture -Roots @('C:\Alpha') | Out-Null
    }
    catch {
        $negativeRejected = $_.Exception.Message -match 'Negative allocated size'
    }
    Assert-True -Condition $negativeRejected -Message 'A negative allocated size was not rejected.'

    $relativeRejected = $false
    try {
        & $scriptPath -CsvPath $fixture -Roots @('relative\root') | Out-Null
    }
    catch {
        $relativeRejected = $_.Exception.Message -match 'must be an absolute path'
    }
    Assert-True -Condition $relativeRejected -Message 'A relative root was not rejected.'

    'PASS: Summarize-WizTreeCsv.ps1'
}
finally {
    if ($resolvedTestRoot.StartsWith($tempRoot, [System.StringComparison]::OrdinalIgnoreCase) -and
        (Test-Path -LiteralPath $ownedMarker) -and
        -not ((Get-Item -LiteralPath $resolvedTestRoot).Attributes -band [System.IO.FileAttributes]::ReparsePoint)) {
        foreach ($file in @($fixture, $invalidFixture, $negativeFixture, $ownedMarker)) {
            if (Test-Path -LiteralPath $file) { Remove-Item -LiteralPath $file -Force }
        }
        Remove-Item -LiteralPath $resolvedTestRoot -Force
    }
}
